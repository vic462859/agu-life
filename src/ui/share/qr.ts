/** 在给定矩形里画二维码：浅底 + 深色模块，内置 2 模块静区。 */
export function drawQr(
  ctx: { fillStyle?: unknown; fillRect(x: number, y: number, w: number, h: number): void },
  x: number,
  y: number,
  size: number,
  light: string,
  dark: string
): void {
  const margin = 2
  const u = size / (QR_MODULES + margin * 2)
  ctx.fillStyle = light
  ctx.fillRect(x, y, size, size)
  ctx.fillStyle = dark
  for (let r = 0; r < QR_MODULES; r++) {
    const row = QR_ROWS[r]
    for (let c = 0; c < QR_MODULES; c++) {
      if (row.charCodeAt(c) === 35) ctx.fillRect(x + (c + margin) * u, y + (r + margin) * u, Math.ceil(u), Math.ceil(u))
    }
  }
}
